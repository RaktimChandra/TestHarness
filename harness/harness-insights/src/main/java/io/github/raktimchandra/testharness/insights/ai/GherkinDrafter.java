package io.github.raktimchandra.testharness.insights.ai;

import io.cucumber.gherkin.GherkinParser;
import io.cucumber.messages.types.Envelope;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Drafts a Gherkin feature from a user story. The draft is <b>only ever written under
 * {@code target/ai-drafts/}</b>, starts with a banner saying who wrote it and that a person must
 * review it, carries a {@code @draft} tag, and is parsed before it is saved: a draft that is not
 * valid Gherkin is still saved, but its banner says so. Nothing is committed or run.
 */
public final class GherkinDrafter {

    public record Draft(Path file, String feature, boolean parses, Optional<String> parseError, int scenarios) {}

    static final String SYSTEM = """
            You write Cucumber Gherkin for an existing test suite. Rules:
            - Output one Feature in a single ```gherkin code block and nothing else.
            - Tag the feature @draft.
            - Reuse the existing step phrases listed below verbatim whenever one fits; write a new
              step only when none fits, and keep new steps in the same style.
            - Cover the happy path, the boundaries and the error cases the story implies; use a
              Scenario Outline with Examples for value tables.
            - Do not invent business rules the story does not state; if something is unclear, add a
              "# QUESTION:" comment instead of guessing.
            """;

    private final LlmClient llm;
    private final Path outputDir;

    public GherkinDrafter(LlmClient llm, Path outputDir) {
        this.llm = llm;
        this.outputDir = outputDir;
    }

    public Draft draft(String userStory, List<Path> existingFeatures) {
        Set<String> steps = existingSteps(existingFeatures);
        String user = "User story:\n" + userStory.strip() + "\n\nExisting step phrases:\n"
                + String.join("\n", steps);
        String feature = Drafts.codeBlock(llm.complete(SYSTEM, user, List.of()));
        Optional<String> error = parseError(feature);
        int scenarios = error.isPresent() ? 0 : countScenarios(feature);
        String banner = "# DRAFT — generated by " + llm.describe() + " on " + Instant.now() + "\n"
                + "# Needs human review before it is moved into src/test/resources/features. Not run, not committed.\n"
                + (error.map(e -> "# WARNING: this draft is not valid Gherkin: " + e.replace('\n', ' ') + "\n")
                        .orElse(""))
                + "# Story: " + userStory.strip().replace('\n', ' ') + "\n\n";
        Path file = outputDir.resolve(Drafts.slug(firstLine(userStory)) + ".feature");
        try {
            Files.createDirectories(outputDir);
            Files.writeString(file, banner + feature + "\n", StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return new Draft(file, feature, error.isEmpty(), error, scenarios);
    }

    /** Distinct step lines (without keywords) from existing feature files, so the model reuses them. */
    static Set<String> existingSteps(List<Path> features) {
        Set<String> steps = new LinkedHashSet<>();
        for (Path f : features) {
            try (Stream<String> lines = Files.lines(f)) {
                lines.map(String::strip)
                        .filter(l -> l.matches("^(Given|When|Then|And|But) .*"))
                        .map(l -> l.replaceFirst("^(Given|When|Then|And|But) ", ""))
                        .forEach(steps::add);
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }
        return steps;
    }

    static Optional<String> parseError(String feature) {
        Stream<Envelope> out = GherkinParser.builder().includeSource(false).includePickles(false).build()
                .parse("draft.feature", feature.getBytes(StandardCharsets.UTF_8));
        return out.flatMap(e -> e.getParseError().stream()).map(p -> p.getMessage()).findFirst();
    }

    static int countScenarios(String feature) {
        return (int) GherkinParser.builder().includeSource(false).includeGherkinDocument(false).build()
                .parse("draft.feature", feature.getBytes(StandardCharsets.UTF_8))
                .filter(e -> e.getPickle().isPresent()).count();
    }

    private static String firstLine(String s) {
        String line = s.strip().lines().findFirst().orElse("draft");
        return line.length() > 80 ? line.substring(0, 80) : line;
    }
}
